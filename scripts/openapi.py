"""Writes the OpenAPI documents of the run, daemon and hub APIs to ui-web/openapi/ (committed).

They are the contract between the Python servers and the web UI: the C# models are generated from them, and
tests/server/test_openapi_snapshot.py fails when the live APIs differ from them. After changing an API, run:

    uv run python scripts/openapi.py
"""

import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "ui-web" / "openapi"


def documents() -> dict[str, dict[str, Any]]:
    """The current OpenAPI document of each API, without the clabe version (it changes with every release)."""
    from clabe.daemon import DaemonSettings, create_daemon
    from clabe.hub import Fleet, HubSettings, create_hub_app
    from clabe.server import create_app
    from clabe.workflow import Run, Workflow

    apps = {
        "run": create_app(Run(Workflow("openapi")), static_dir=None),
        "daemon": create_daemon(DaemonSettings()),
        "hub": create_hub_app(Fleet(HubSettings()), static_dir=None, poll=False),
    }
    docs = {}
    for name, app in apps.items():
        doc = app.openapi()
        doc["info"].pop("version", None)
        docs[name] = doc
    return docs


def render(document: dict[str, Any]) -> str:
    """A document as stable, diff-friendly JSON."""
    return json.dumps(document, indent=2, sort_keys=True) + "\n"


#: Where the generated C# models go, one file per API.
MODELS = ROOT / "ui-web" / "Models" / "Generated"

#: Schemas the web UI maps by hand (the run's events are one discriminated union, ``RunEvent``).
_HAND_MAPPED = {"PromptOpened": "Clabe.Web.Models.RunEvent"}


def _pascal(name: str) -> str:
    """``snake_case`` → ``PascalCase``."""
    return "".join(part[:1].upper() + part[1:] for part in name.split("_") if part)


def _is_event(schema: dict[str, Any]) -> bool:
    """Whether a schema is one of the run's events (they carry a sequence number)."""
    return "seq" in schema.get("properties", {})


def _csharp_type(schema: dict[str, Any], schemas: dict[str, Any]) -> tuple[str, bool]:
    """The C# type of a property schema, and whether it can be null."""
    if "$ref" in schema:
        name = schema["$ref"].rsplit("/", 1)[-1]
        if name in _HAND_MAPPED:
            return _HAND_MAPPED[name], False
        target = schemas[name]
        return ("string", False) if "enum" in target else (name, False)
    variants = schema.get("anyOf")
    if variants:
        concrete = [v for v in variants if v.get("type") != "null"]
        nullable = len(concrete) < len(variants)
        if len(concrete) == 1:
            kind, _ = _csharp_type(concrete[0], schemas)
            return kind, nullable
        return "System.Text.Json.Nodes.JsonNode", True
    kind = schema.get("type")
    if "enum" in schema or "const" in schema:
        return "string", False
    if kind == "string":
        return ("DateTimeOffset", False) if schema.get("format") == "date-time" else ("string", False)
    if kind == "integer":
        return "long", False
    if kind == "number":
        return "double", False
    if kind == "boolean":
        return "bool", False
    if kind == "array":
        item, _ = _csharp_type(schema.get("items", {}), schemas)
        return f"List<{item}>", False
    if kind == "object" and "properties" not in schema:
        return "System.Text.Json.Nodes.JsonObject", False
    return "System.Text.Json.Nodes.JsonNode", True


def _literal(value: Any, kind: str) -> str | None:
    """A JSON default as a C# literal of type ``kind``, for scalars; ``None`` when there is none to give."""
    if value is None:
        return None
    if kind == "bool" and isinstance(value, bool):
        return "true" if value else "false"
    if kind in ("long", "double") and isinstance(value, int | float) and not isinstance(value, bool):
        return repr(value)
    if kind == "string" and isinstance(value, str):
        return json.dumps(value)
    return None


def csharp(api: str, document: dict[str, Any]) -> str:
    """C# records for the object schemas of ``document`` (events excepted), in ``Clabe.Web.Api.<Api>``."""
    schemas = document["components"]["schemas"]
    lines = [
        "// <auto-generated>",
        f"// Generated by scripts/openapi.py from ui-web/openapi/{api}.json. Do not edit: change the Python models,",
        "// then run `uv run python scripts/openapi.py`.",
        "// </auto-generated>",
        "#nullable enable",
        "using System.Text.Json.Serialization;",
        "",
        f"namespace Clabe.Web.Api.{_pascal(api)};",
    ]
    for name in sorted(schemas):
        schema = schemas[name]
        if name in _HAND_MAPPED or "properties" not in schema or _is_event(schema):
            continue
        required = set(schema.get("required", []))
        parameters = []
        for prop, prop_schema in schema["properties"].items():
            kind, nullable = _csharp_type(prop_schema, schemas)
            default = ""
            if prop not in required:
                literal = _literal(prop_schema.get("default"), kind)
                # Responses always carry a field with a default: a scalar default keeps it non-nullable.
                if literal is not None and not nullable:
                    default = f" = {literal}"
                else:
                    nullable, default = True, " = null"
            suffix = "?" if nullable and not kind.endswith("?") else ""
            parameters.append(f'    [property: JsonPropertyName("{prop}")] {kind}{suffix} {_pascal(prop)}{default}')
        # Required parameters must come before optional ones in a C# positional record.
        parameters.sort(key=lambda p: " = " in p)
        doc = schema.get("description", "").split("\n", 1)[0].replace("<", "&lt;").replace(">", "&gt;")
        summary = [f"/// <summary>{doc}</summary>"] if doc else []
        lines += ["", *summary, f"public sealed record {name}(", ",\n".join(parameters) + ");"]
    return "\n".join(lines) + "\n"


def main() -> int:
    """Writes the documents and the C# models generated from them."""
    OUT.mkdir(parents=True, exist_ok=True)
    MODELS.mkdir(parents=True, exist_ok=True)
    for name, document in documents().items():
        (OUT / f"{name}.json").write_text(render(document), encoding="utf-8", newline="\n")
        (MODELS / f"{_pascal(name)}.g.cs").write_text(csharp(name, document), encoding="utf-8", newline="\n")
        print(
            f"wrote {OUT.relative_to(ROOT) / f'{name}.json'} and {MODELS.relative_to(ROOT) / f'{_pascal(name)}.g.cs'}"
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
